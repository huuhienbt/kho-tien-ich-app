// Keep the proven group ledger rules shared with Apps Script. Only storage/runtime adapters change.
import fs from 'node:fs';
const input = new URL('../../../NhomHoc.gs', import.meta.url);
const source = fs.readFileSync(input, 'utf8');
const omitted = new Set(['nhBook_', 'setupNhomHoc', 'nhTable_', 'nhRows_', 'nhWrite_', 'nhToday_', 'nhHash_', 'handleNhomHoc', 'nhCloudflareActive_']);
// All declarations in the shared source are top-level functions beginning in column 1.
const functions = source.split(/(?=^function )/m).filter(chunk => /^function /.test(chunk) && !omitted.has(chunk.match(/^function (\w+)/)[1])).map(chunk => chunk.trim().replaceAll('Utilities.getUuid()', 'randomUUID()').replaceAll('new Date().toISOString()', 'requestNow'));
const schema = source.match(/const NH_SCHEMA = \{[\s\S]*?\n\};/)[0];
const dispatch = source.slice(source.indexOf("    if(action==='nh_boot') result=nhBoot_(ctx);"), source.indexOf('    if(write)SpreadsheetApp.flush();'));
const generated = `// Generated by scripts/build-engine.mjs from NhomHoc.gs. Do not edit the ledger rules here.
import {createHash, randomUUID} from 'node:crypto';
export const VERSION = '9.5.0';
export ${schema}
export const ACTIONS = ['nh_boot','nh_view','nh_group_save','nh_students_save','nh_member_save','nh_session_save','nh_attendance_save','nh_attendance_batch_save','nh_schedule_preview','nh_sessions_plan','nh_receipt_save','nh_receipt_void','nh_close_month','nh_reopen_month'];
export const READ_ACTIONS = ['nh_boot','nh_view','nh_schedule_preview'];
export const primaryKeys = name => name === 'DiemDanh' ? ['ma_buoi','ma_hoc_sinh'] : [NH_SCHEMA[name][0]];
export function runAction(tables, user, action, data = {}, today, teachers = [], requestNow = new Date().toISOString()) {
  if (user?.role !== 'admin') throw new Error('Chỉ tài khoản quản trị được xem và quản lý nhóm học.');
  if (!ACTIONS.includes(action)) throw new Error('Lệnh nhóm học không hợp lệ.');
  const NH_VERSION = VERSION;
  const ctx = {admin: true, user, tables}, dirty = {};
  const getSheetObjects = () => teachers;
  const cleanText = (value, maxLength) => String(value || '').replace(/[\\u0000-\\u001F\\u007F]/g,' ').replace(/\\s+/g,' ').trim().slice(0,maxLength || 500);
  const nhToday_ = () => today;
  const nhHash_ = value => createHash('sha256').update(JSON.stringify(value)).digest('base64url');
  const nhRows_ = (ctx, name) => ctx.tables[name] || (ctx.tables[name] = []);
  function nhWrite_(ctx, name, items) {
    if (!items.length) return;
    const rows = nhRows_(ctx, name), keys = primaryKeys(name);
    const writes = dirty[name] || (dirty[name] = new Map());
    for (const item of items) {
      const key = JSON.stringify(keys.map(k => item[k]));
      const index = rows.findIndex(row => keys.every(k => row[k] === item[k]));
      if (index < 0) { item._row = rows.length + 2; rows.push(item); }
      else { item._row = rows[index]._row; rows[index] = item; }
      writes.set(key, Object.fromEntries(NH_SCHEMA[name].map(h => [h,item[h] ?? ''])));
    }
  }
${functions.join('\n\n')}
  let result;
${dispatch}
  return {result, dirty: Object.fromEntries(Object.entries(dirty).map(([name,rows]) => [name,[...rows.values()]]))};
}
`;
const output = new URL('../src/engine.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output,'utf8') !== generated) throw new Error('Ledger engine out of date. Run npm run engine.');
} else fs.writeFileSync(output, generated);
